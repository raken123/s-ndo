#!/usr/bin/env python3
"""mkdesktop.py — the three desktop builds: .deb, .exe and .dmg.

None of them ship a browser engine. They ship build/host.c, which serves the
embedded game from 127.0.0.1 and opens the machine's own browser on it in an
app window. That keeps every download about a megabyte instead of ninety, and
— because http://127.0.0.1 is a secure context and file:// is not — it is what
makes WebXR work on the desktop at all.

    python3 build/mkdesktop.py [--skip-win] [--skip-mac] [--skip-deb]

Needs: cc, x86_64-w64-mingw32-gcc (+ windres), dpkg-deb, genisoimage.
"""
import argparse
import gzip
import hashlib
import os
import pathlib
import shutil
import stat
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"
ICONS = DIST / "icons"
WORK = ROOT / "build" / ".desktop"
VERSION = (ROOT / "VERSION").read_text().strip()

MAINTAINER = "AI Judge <aijudge@example.invalid>"
DESCRIPTION_SHORT = "An AI drum robot judges you and a stranger"
DESCRIPTION_LONG = (
    " Join the line in the Hall of Small Grievances and wait until you are\n"
    " standing next to the AI drum robot. It poses a case, you and a random\n"
    " opponent each make yours, and it rules. It holds two guns — one for each\n"
    " of you — and the loser gets shot.\n"
    " .\n"
    " The hall runs in your own browser: this package serves the game from\n"
    " 127.0.0.1 and opens it in an app window, so nothing is bundled twice and\n"
    " WebXR headsets work."
)


def run(cmd, **kw):
    r = subprocess.run([str(c) for c in cmd], capture_output=True, text=True, **kw)
    if r.returncode != 0:
        sys.exit("! %s failed\n%s\n%s" % (cmd[0], r.stdout[-3000:], r.stderr[-3000:]))
    return r


def have(tool):
    return shutil.which(tool) is not None


def embed_game() -> pathlib.Path:
    """Writes the gzip-compressed game out as a C header."""
    html = (DIST / "aijudge.html").read_bytes()
    gz = gzip.compress(html, 9)
    WORK.mkdir(parents=True, exist_ok=True)
    out = WORK / "aijudge_game.h"
    rows = ["/* generated by build/mkdesktop.py — do not edit */",
            "static const unsigned char AIJUDGE_HTML_GZ[] = {"]
    for i in range(0, len(gz), 24):
        rows.append("  " + ",".join(str(b) for b in gz[i:i + 24]) + ",")
    rows += ["};",
             f"#define AIJUDGE_HTML_GZ_LEN {len(gz)}u",
             f'#define AIJUDGE_VERSION "{VERSION}"', ""]
    out.write_text("\n".join(rows))
    print(f"  game payload      {len(html)/1024:7.1f} KB → {len(gz)/1024:.1f} KB gzip")
    return out


# ---------------------------------------------------------------- Linux

def build_deb(incdir):
    pkg = WORK / "deb"
    if pkg.exists():
        shutil.rmtree(pkg)

    binary = WORK / "aijudge"
    # Static so the package runs on distributions older than the build host.
    run(["cc", "-O2", "-static", "-Wall", "-I", incdir,
         "-o", binary, ROOT / "build" / "host.c"])
    run(["strip", binary])

    (pkg / "opt/aijudge").mkdir(parents=True)
    (pkg / "usr/bin").mkdir(parents=True)
    (pkg / "usr/share/applications").mkdir(parents=True)
    (pkg / "DEBIAN").mkdir(parents=True)

    shutil.copy(binary, pkg / "opt/aijudge/aijudge")
    os.chmod(pkg / "opt/aijudge/aijudge", 0o755)
    os.symlink("/opt/aijudge/aijudge", pkg / "usr/bin/aijudge")

    for size in (48, 64, 128, 256, 512):
        d = pkg / f"usr/share/icons/hicolor/{size}x{size}/apps"
        d.mkdir(parents=True, exist_ok=True)
        shutil.copy(ICONS / f"icon-{size}.png", d / "aijudge.png")

    (pkg / "usr/share/applications/aijudge.desktop").write_text(
        "[Desktop Entry]\n"
        "Type=Application\n"
        "Name=AI Judge\n"
        f"Comment={DESCRIPTION_SHORT}\n"
        "Exec=/opt/aijudge/aijudge\n"
        "Icon=aijudge\n"
        "Terminal=false\n"
        "Categories=Game;ActionGame;\n"
        "Keywords=game;ai;judge;multiplayer;vr;\n"
        "StartupNotify=true\n"
    )

    size_kb = sum(f.stat().st_size for f in pkg.rglob("*") if f.is_file()) // 1024
    (pkg / "DEBIAN/control").write_text(
        "Package: aijudge\n"
        f"Version: {VERSION}\n"
        "Section: games\n"
        "Priority: optional\n"
        "Architecture: amd64\n"
        f"Installed-Size: {size_kb}\n"
        f"Maintainer: {MAINTAINER}\n"
        "Recommends: chromium | chromium-browser | google-chrome-stable\n"
        "Suggests: xdg-utils\n"
        f"Description: {DESCRIPTION_SHORT}\n{DESCRIPTION_LONG}\n"
    )

    out = DIST / f"aijudge_{VERSION}_amd64.deb"
    if out.exists():
        out.unlink()
    run(["dpkg-deb", "--root-owner-group", "-Zxz", "--build", pkg, out])
    return out


# ---------------------------------------------------------------- Windows

def build_exe(incdir):
    rc = WORK / "aijudge.rc"
    ver = VERSION.split(".") + ["0", "0", "0"]
    rc.write_text(
        'IDI_ICON1 ICON "%s"\n\n' % (ICONS / "icon.ico").as_posix() +
        "1 VERSIONINFO\n"
        f"FILEVERSION {ver[0]},{ver[1]},{ver[2]},0\n"
        f"PRODUCTVERSION {ver[0]},{ver[1]},{ver[2]},0\n"
        "BEGIN\n"
        '  BLOCK "StringFileInfo"\n'
        "  BEGIN\n"
        '    BLOCK "040904b0"\n'
        "    BEGIN\n"
        '      VALUE "CompanyName", "AI Judge"\n'
        '      VALUE "FileDescription", "AI Judge"\n'
        f'      VALUE "FileVersion", "{VERSION}"\n'
        '      VALUE "InternalName", "aijudge"\n'
        '      VALUE "OriginalFilename", "AIJudge.exe"\n'
        '      VALUE "ProductName", "AI Judge"\n'
        f'      VALUE "ProductVersion", "{VERSION}"\n'
        "    END\n"
        "  END\n"
        '  BLOCK "VarFileInfo"\n'
        "  BEGIN\n"
        '    VALUE "Translation", 0x409, 1200\n'
        "  END\n"
        "END\n"
    )
    res = WORK / "aijudge.res.o"
    run(["x86_64-w64-mingw32-windres", rc, "-O", "coff", "-o", res])

    out = DIST / f"AIJudge-{VERSION}-win-x64.exe"
    run(["x86_64-w64-mingw32-gcc", "-O2", "-Wall", "-I", incdir,
         "-o", out, ROOT / "build" / "host.c", res,
         "-lws2_32", "-lshell32",
         "-mwindows",          # no console window behind the game
         "-static",            # no libgcc/winpthread DLLs to ship
         "-s"])
    return out


# ---------------------------------------------------------------- macOS

MAC_LAUNCHER = r"""#!/bin/sh
# AI Judge — macOS launcher.
#
# Serves the bundled game from 127.0.0.1 when a Python is available, because
# http://127.0.0.1 is a secure context and file:// is not; localStorage and
# WebXR need that. Falls back to opening the file directly.

set -u
HERE=$(cd "$(dirname "$0")/../Resources" && pwd)
GAME="$HERE/aijudge.html"

BROWSER=""
for app in \
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" \
  "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge" \
  "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser" \
  "/Applications/Chromium.app/Contents/MacOS/Chromium"
do
  [ -x "$app" ] && { BROWSER="$app"; break; }
done

PY=$(command -v python3 2>/dev/null || true)
if [ -n "$PY" ]; then
  PORT=$("$PY" - <<'EOF'
import socket
s = socket.socket()
s.bind(("127.0.0.1", 0))
print(s.getsockname()[1])
s.close()
EOF
)
  SERVE_DIR=$(mktemp -d /tmp/aijudge.XXXXXX)
  cp "$GAME" "$SERVE_DIR/index.html"
  ( cd "$SERVE_DIR" && "$PY" -m http.server "$PORT" --bind 127.0.0.1 >/dev/null 2>&1 ) &
  SERVER_PID=$!
  trap 'kill $SERVER_PID 2>/dev/null; rm -rf "$SERVE_DIR"' EXIT INT TERM
  URL="http://127.0.0.1:$PORT/"
  sleep 1
else
  URL="file://$GAME"
fi

if [ -n "$BROWSER" ]; then
  "$BROWSER" --app="$URL" \
    --user-data-dir="$HOME/Library/Application Support/AIJudge/profile" \
    --no-first-run --no-default-browser-check --window-size=1280,820
else
  # No Chromium-family browser: Safari it is, and the script waits for the user.
  open "$URL"
  [ -n "$PY" ] && { echo "AI Judge is serving at $URL — close this window when done."; wait $SERVER_PID; }
fi
"""


def build_dmg():
    app = WORK / "dmgroot" / "AIJudge.app"
    if (WORK / "dmgroot").exists():
        shutil.rmtree(WORK / "dmgroot")
    (app / "Contents/MacOS").mkdir(parents=True)
    (app / "Contents/Resources").mkdir(parents=True)

    launcher = app / "Contents/MacOS/AIJudge"
    launcher.write_text(MAC_LAUNCHER)
    launcher.chmod(launcher.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    shutil.copy(DIST / "aijudge.html", app / "Contents/Resources/aijudge.html")
    shutil.copy(ICONS / "icon.icns", app / "Contents/Resources/icon.icns")

    (app / "Contents/Info.plist").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" '
        '"http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n'
        '<plist version="1.0">\n<dict>\n'
        "  <key>CFBundleName</key><string>AI Judge</string>\n"
        "  <key>CFBundleDisplayName</key><string>AI Judge</string>\n"
        "  <key>CFBundleExecutable</key><string>AIJudge</string>\n"
        "  <key>CFBundleIdentifier</key><string>com.aijudge.game</string>\n"
        f"  <key>CFBundleVersion</key><string>{VERSION}</string>\n"
        f"  <key>CFBundleShortVersionString</key><string>{VERSION}</string>\n"
        "  <key>CFBundleIconFile</key><string>icon</string>\n"
        "  <key>CFBundlePackageType</key><string>APPL</string>\n"
        "  <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>\n"
        "  <key>LSMinimumSystemVersion</key><string>11.0</string>\n"
        "  <key>LSApplicationCategoryType</key><string>public.app-category.games</string>\n"
        "  <key>NSHighResolutionCapable</key><true/>\n"
        "  <key>NSSupportsAutomaticGraphicsSwitching</key><true/>\n"
        "</dict>\n</plist>\n"
    )

    # a drag-to-install target, the way every mac disk image does it
    os.symlink("/Applications", WORK / "dmgroot" / "Applications")
    (WORK / "dmgroot" / "README.txt").write_text(
        "AI Judge " + VERSION + "\n\n"
        "Drag AIJudge.app onto the Applications folder.\n\n"
        "The bundle is not code-signed or notarised, so the first launch needs\n"
        "Control-click -> Open (or: xattr -dr com.apple.quarantine /Applications/AIJudge.app).\n\n"
        "AI Judge runs in your own browser. Chrome, Edge, Brave or Chromium give\n"
        "it a proper app window; otherwise it opens in your default browser.\n"
    )

    out = DIST / f"AIJudge-{VERSION}-macos.dmg"
    if out.exists():
        out.unlink()
    # Rock Ridge keeps the +x bit on the launcher and the /Applications symlink;
    # -apple adds the Apple extensions the Finder expects.
    run(["genisoimage", "-quiet", "-V", "AI Judge", "-D", "-R", "-apple",
         "-no-pad", "-o", out, WORK / "dmgroot"])
    return out


# ----------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--skip-deb", action="store_true")
    ap.add_argument("--skip-win", action="store_true")
    ap.add_argument("--skip-mac", action="store_true")
    args = ap.parse_args()

    if not (DIST / "aijudge.html").exists():
        sys.exit("! run `python3 build/mkweb.py` first")
    if not (ICONS / "icon.ico").exists():
        sys.exit("! run `node build/mkicon.js` first")

    print(f"AI Judge {VERSION} — desktop builds")
    WORK.mkdir(parents=True, exist_ok=True)
    header = embed_game()
    incdir = header.parent

    built = []
    if not args.skip_deb:
        if not have("dpkg-deb"):
            print("  ! dpkg-deb missing, skipping the .deb")
        else:
            built.append(("Debian / Ubuntu x86-64", build_deb(incdir)))
    if not args.skip_win:
        if not have("x86_64-w64-mingw32-gcc"):
            print("  ! mingw-w64 missing, skipping the .exe")
        else:
            built.append(("Windows 10/11 x86-64", build_exe(incdir)))
    if not args.skip_mac:
        if not have("genisoimage"):
            print("  ! genisoimage missing, skipping the .dmg")
        else:
            built.append(("macOS 11+", build_dmg()))

    for label, path in built:
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        print(f"  {path.name:<34} {path.stat().st_size/1024:7.1f} KB   {label}")
        print(f"  {'':34} {digest}")

    shutil.rmtree(WORK, ignore_errors=True)


if __name__ == "__main__":
    main()
