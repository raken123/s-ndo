let lang = 'sv';

export function setLang(l) { lang = STRINGS[l] ? l : 'sv'; document.documentElement.lang = lang; }
export function getLang() { return lang; }

export function t(key, ...args) {
  const v = STRINGS[lang][key] ?? STRINGS.sv[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}

// Plockar rätt språk ur ett {sv, en}-objekt.
export function L(obj) { return obj ? (obj[lang] ?? obj.sv) : ''; }
