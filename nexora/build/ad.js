// Renders a Nexora short ad (1080x1920, 30 fps) from a page in nexora/marketing/.
//   node nexora/build/ad.js [launch15.html | ad.html | plans.html]
// The page declares window.AD = { out, thumb, thumbAt, duration, music, games, extras, sounds, sfx }
// and draws every frame in __adFrame(t, dt).
// Everything in the ad is AI output. With NEXORA_ANTHROPIC_KEY set, the games, 3D models,
// sprites, music and sound effects are generated through the app's own AI models.
// Without a key the examples in marketing/examples/ are used (games, meshes.json,
// sprites/, music.json, sfx.json – the same formats the models return).
// Needs ffmpeg with libx264 on PATH (or FFMPEG=/path/to/ffmpeg) and the Inter font
// in build/.cache (downloaded on first run). Every frame is rendered on a virtual
// clock, so the video is perfectly smooth no matter how slow the machine is.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
let pw;
try { pw = require('playwright'); } catch (e) { pw = require('/opt/node22/lib/node_modules/playwright'); }

const ROOT = path.join(__dirname, '..');
const CACHE = path.join(__dirname, '.cache');
const FRAMES = path.join(CACHE, 'ad-frames');
const OUT = path.join(ROOT, 'marketing');
const FFMPEG = process.env.FFMPEG || 'ffmpeg';
const FPS = 30;
const PAGE = process.argv[2] || 'ad.html';

// Replaces time in a game iframe: rAF, timers and clocks only move when __advance(ms) is called.
const CLOCK = '<script>(function(){var now=0,q=[],T=[],id=0;' +
  'performance.now=function(){return now};Date.now=function(){return 1790000000000+now};' +
  'window.requestAnimationFrame=function(cb){q.push(cb);return q.length};window.cancelAnimationFrame=function(){};' +
  'window.setTimeout=function(f,ms){T.push({t:now+(ms||0),f:f,id:++id});return id};' +
  'window.setInterval=function(f,ms){T.push({t:now+ms,f:f,iv:ms,id:++id});return id};' +
  'window.clearTimeout=window.clearInterval=function(i){T=T.filter(function(x){return x.id!==i})};' +
  'window.__advance=function(ms){var end=now+ms;for(;;){T.sort(function(a,b){return a.t-b.t});if(!T.length||T[0].t>end)break;' +
  'var x=T.shift();now=x.t;try{typeof x.f==="function"&&x.f()}catch(e){}if(x.iv){x.t+=x.iv;T.push(x)}}' +
  'now=end;var c=q.splice(0);c.forEach(function(f){try{f(now)}catch(e){}})};})();</' + 'script>';

(async () => {
  const font = path.join(CACHE, 'InterVariable.ttf');
  if (!fs.existsSync(font)) {
    fs.mkdirSync(CACHE, { recursive: true });
    execFileSync('curl', ['-sSL', '-o', path.join(CACHE, 'inter.zip'), 'https://github.com/rsms/inter/releases/download/v4.1/Inter-4.1.zip']);
    execFileSync('unzip', ['-o', '-j', path.join(CACHE, 'inter.zip'), 'InterVariable.ttf', '-d', CACHE]);
  }
  fs.rmSync(FRAMES, { recursive: true, force: true });
  fs.mkdirSync(FRAMES, { recursive: true });
  const browser = await pw.chromium.launch();
  const probe = await browser.newPage();
  await probe.goto('file://' + path.join(OUT, PAGE));
  const AD = await probe.evaluate(() => window.AD);
  await probe.close();
  const DURATION = AD.duration;

  // 1. games, models, sprites and audio: generated by the app's AI, or the saved AI examples
  const EX = path.join(OUT, 'examples'), KEY = process.env.NEXORA_ANTHROPIC_KEY || '';
  const prompt = v => (Array.isArray(v) ? v[0] : v), dimOf = v => (Array.isArray(v) && v[1]) || '2d';
  const ex = AD.extras || {}, sounds = Object.assign({ power: 'ett glatt powerup-ljud', coin: 'ett myntljud', laser: 'ett snabbt swoosh-ljud' }, AD.sounds || {});
  const input = { key: KEY, games: {}, meshes: [], sprites: [], music: null, sfx: {} };
  if (!KEY) {
    for (const id of Object.keys(AD.games)) {
      const f = path.join(EX, 'games', id + '.html');
      if (!fs.existsSync(f)) throw new Error('Exempelspelet ' + path.relative(ROOT, f) + ' saknas. Sätt NEXORA_ANTHROPIC_KEY så skriver AI:n det.');
      input.games[id] = fs.readFileSync(f, 'utf8');
    }
    const meshes = JSON.parse(fs.readFileSync(path.join(EX, 'meshes.json'), 'utf8'));
    input.meshes = (ex.meshes || []).map((m, i) => meshes[i]);
    input.sprites = (ex.sprites || []).map(([file]) => fs.readFileSync(path.join(EX, 'sprites', file + '.svg'), 'utf8'));
    input.music = JSON.parse(fs.readFileSync(path.join(EX, 'music.json'), 'utf8'));
    input.sfx = JSON.parse(fs.readFileSync(path.join(EX, 'sfx.json'), 'utf8'));
  }
  console.log(KEY ? 'generating everything with the Nexora AI models…' : 'using the AI examples in marketing/examples/');
  const app = await browser.newPage();
  await app.goto('file://' + path.join(ROOT, 'index.html'));
  const assets = await app.evaluate(async ([AD, input, sounds, games]) => {
    const AI = NexoraAI, M = NexoraMedia, st = { provider: 'anthropic', anthropicKey: input.key, openaiModels: {} };
    const out = { games: {}, extras: { meshes: [], sprites: [], nx3d: nxShade.toString() + '\n' + Nx3D.toString() } };
    if (input.key) {
      for (const [id, [p, dim]] of Object.entries(games)) out.games[id] = (await AI.generateGame(st, 'pro', p, { dim, features: ['sfx'] })).html;
      for (const p of (AD.extras || {}).meshes || []) out.extras.meshes.push(M.cleanMesh(await AI.mesh(st, p)));
      for (const [, p, style] of (AD.extras || {}).sprites || []) out.extras.sprites.push((await AI.image(st, p, null, null, { style, frames: 4 })).svg);
      input.music = await AI.music(st, AD.music);
      for (const [k, p] of Object.entries(sounds)) input.sfx[k] = await AI.sfx(st, p);
    } else {
      out.games = input.games;
      out.extras.meshes = input.meshes.map(M.cleanMesh);
      out.extras.sprites = input.sprites;
    }
    const b64 = async blob => { const b = new Uint8Array(await blob.arrayBuffer()); let s = ''; for (let i = 0; i < b.length; i += 32768) s += String.fromCharCode.apply(null, b.subarray(i, i + 32768)); return btoa(s); };
    out.music = await b64((await M.renderMusic(input.music, AD.duration + 1)).blob);
    for (const k of Object.keys(sounds)) out[k] = await b64(await M.renderSfx(input.sfx[k]));
    return out;
  }, [AD, input, sounds, Object.fromEntries(Object.entries(AD.games).map(([id, v]) => [id, [prompt(v), dimOf(v)]]))]);
  await app.close();
  for (const k of ['music'].concat(Object.keys(sounds))) fs.writeFileSync(path.join(CACHE, 'ad-' + k + '.wav'), Buffer.from(assets[k], 'base64'));

  // 2. frames
  const page = await browser.newPage({ viewport: { width: 1080, height: 1920 }, deviceScaleFactor: 1 });
  page.on('pageerror', e => console.error('page error:', e.message));
  await page.goto('file://' + path.join(OUT, PAGE));
  await page.evaluate(() => document.fonts.ready);
  const withClock = {};
  // the games run on the ad's clock, in their attract/demo mode where they play themselves
  const DEMO = '<script>window.NEXORA_DEMO=true;</' + 'script>';
  for (const [k, html] of Object.entries(assets.games)) withClock[k] = /<head(\s[^>]*)?>/i.test(html) ? html.replace(/<head(\s[^>]*)?>/i, m => m + CLOCK + DEMO) : CLOCK + DEMO + html;
  await page.evaluate(([g, x]) => window.__setup(g, x), [withClock, assets.extras]);
  const n = FPS * DURATION;
  const thumbFrame = Math.min(n - 1, Math.round((AD.thumbAt != null ? AD.thumbAt : DURATION) * FPS));
  for (let i = 0; i < n; i++) {
    await page.evaluate(([t, dt]) => window.__adFrame(t, dt), [i / FPS, 1 / FPS]);
    const f = path.join(FRAMES, 'f' + String(i).padStart(5, '0') + '.jpg');
    await page.screenshot({ path: f, type: 'jpeg', quality: 92 });
    if (i === thumbFrame) fs.copyFileSync(f, path.join(OUT, AD.thumb));
    if (i % 90 === 0) console.log('frame', i, '/', n);
  }
  await browser.close();

  // 3. encode: music + sound effects on the cuts
  const out = path.join(OUT, AD.out);
  const sfx = AD.sfx;
  const args = ['-y', '-loglevel', 'error', '-framerate', String(FPS), '-i', path.join(FRAMES, 'f%05d.jpg'), '-i', path.join(CACHE, 'ad-music.wav')];
  sfx.forEach(([k]) => args.push('-i', path.join(CACHE, 'ad-' + k + '.wav')));
  let filter = `[1:a]volume=0.85,afade=t=in:d=0.4,afade=t=out:st=${DURATION - 1.8}:d=1.8[m]`;
  const labels = ['[m]'];
  sfx.forEach(([, at], i) => { filter += `;[${i + 2}:a]adelay=${Math.round(at * 1000)}|${Math.round(at * 1000)},volume=0.7[s${i}]`; labels.push(`[s${i}]`); });
  filter += `;${labels.join('')}amix=inputs=${labels.length}:normalize=0,alimiter=limit=0.95[a]`;
  args.push('-filter_complex', filter, '-map', '0:v', '-map', '[a]', '-t', String(DURATION),
    '-c:v', 'libx264', '-preset', 'slow', '-crf', '19', '-pix_fmt', 'yuv420p', '-profile:v', 'high', '-r', String(FPS),
    '-c:a', 'aac', '-b:a', '192k', '-ar', '48000', '-movflags', '+faststart', out);
  execFileSync(FFMPEG, args, { stdio: 'inherit' });
  console.log('wrote', out, (fs.statSync(out).size / 1e6).toFixed(1) + ' MB');
})().catch(e => { console.error(e); process.exit(1); });
