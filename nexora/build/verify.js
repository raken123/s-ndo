// Drives the built nexora/index.html in headless Chromium.
//   node nexora/build/verify.js [path/to/nexora.html]
// Screenshots go to $SHOTS (default: nexora/build/shots).
const path = require('path');
const fs = require('fs');
const { execFileSync } = require('child_process');
let pw;
try { pw = require('playwright'); } catch (e) { pw = require('/opt/node22/lib/node_modules/playwright'); }

const FILE = path.resolve(process.argv[2] || path.join(__dirname, '..', 'index.html'));
const SHOTS = process.env.SHOTS || path.join(__dirname, 'shots');
fs.mkdirSync(SHOTS, { recursive: true });
let failed = 0;
const ok = (c, msg) => { console.log((c ? 'PASS ' : 'FAIL ') + msg); if (!c) failed++; };

const PROMPTS = [
  ['Ett plattformsspel i en lavavärld där man hoppar på drakar', '2d', 'platformer'],
  ['Rymdskjutare med neon-tema och bossar', '2d', 'shooter'],
  ['Open world-äventyr i en skog med uppdrag och NPC:er', '2d', 'openworld'],
  ['Orm-spel under vattnet, svårt', '2d', 'snake'],
  ['Blockkross med spöken', '2d', 'breakout'],
  ['Undvik bilar på en ökenväg', '2d', 'dodger'],
  ['Samla diamanter i en godisvärld, två spelare', '2d', 'collector'],
  ['En 3D-löpare på en isväg', '3d', 'runner3d'],
  ['3D arena där man samlar kulor i rymden', '3d', 'arena3d'],
];

(async () => {
  const browser = await pw.chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, acceptDownloads: true });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
  await page.goto('file://' + FILE);
  await page.waitForSelector('header.top');
  ok(await page.evaluate(() => !!(window.Nexora && window.NexoraLocal && window.NexoraAI && window.Nx3D)), 'app globals present');

  for (const r of ['hem', 'studio', 'verktyg', 'spel', 'team', 'modeller', 'priser', 'ladda-ner']) {
    await page.evaluate(x => { location.hash = x; }, r);
    await page.waitForTimeout(250);
    await page.screenshot({ path: path.join(SHOTS, 'view-' + r + '.png'), fullPage: r === 'hem' || r === 'priser' });
  }
  ok(errors.length === 0, 'all views render without errors ' + (errors.length ? JSON.stringify(errors) : ''));

  // plan gating on Free
  await page.evaluate(() => { location.hash = 'studio'; });
  await page.waitForTimeout(200);
  await page.click('.seg button:nth-child(2)');
  ok(await page.$('.modal') !== null, 'Free plan: 3D opens the upgrade dialog');
  await page.keyboard.press('Escape');

  // every template, generated by the real app code and run as a standalone page
  for (const [prompt, dim, want] of PROMPTS) {
    const html = await page.evaluate(([p, d]) => {
      const cfg = NexoraLocal.config(p, { dim: d, music: true, sfx: true, multiplayer: true, quests: true, allowOpenWorld: true });
      window.__cfg = cfg;
      return NexoraLocal.buildHtml(cfg, Nexora.RT);
    }, [prompt, dim]);
    const genre = await page.evaluate(() => window.__cfg.genre);
    ok(genre === want, `"${prompt}" → ${genre}`);
    const g = await ctx.newPage();
    const gErr = [];
    g.on('pageerror', e => gErr.push(e.message));
    await g.setContent(html);
    await g.waitForTimeout(300);
    await g.keyboard.press('Space');
    const keys = ['ArrowRight', 'ArrowUp', 'ArrowLeft', 'Space', 'ArrowDown', 'KeyD', 'KeyW'];
    for (let i = 0; i < 14; i++) {
      const k = keys[i % keys.length];
      await g.keyboard.down(k); await g.waitForTimeout(110); await g.keyboard.up(k);
    }
    const colors = await g.evaluate(() => {
      const c = document.getElementById('c'), x = c.getContext('2d').getImageData(0, 0, c.width, c.height).data, s = new Set();
      for (let i = 0; i < x.length; i += 4 * 97) s.add((x[i] >> 3) + ',' + (x[i + 1] >> 3) + ',' + (x[i + 2] >> 3));
      return s.size;
    });
    await g.screenshot({ path: path.join(SHOTS, 'game-' + want + '.png') });
    ok(gErr.length === 0 && colors > 8, `${want} runs (${colors} colours) ${gErr.join(' | ')}`);
    await g.close();
  }

  // unlock everything and use the Studio UI end to end
  await page.evaluate(() => { localStorage.setItem('nexora.plan', '"enterprise"'); });
  await page.reload();
  await page.evaluate(() => { location.hash = 'studio'; });
  await page.waitForSelector('#prompt');
  await page.fill('#prompt', 'Open world-äventyr i en skog med uppdrag');
  await page.click('text=✨ Skapa spel');
  await page.waitForSelector('.screen iframe', { timeout: 10000 });
  await page.waitForTimeout(800);
  const frame = page.frames().find(f => f !== page.mainFrame());
  ok(!!frame && !!(await frame.$('canvas')), 'Studio shows the generated game in the preview');
  await page.screenshot({ path: path.join(SHOTS, 'studio-generated.png') });
  const saved = await page.evaluate(() => Nexora.games.all().then(a => a.length));
  ok(saved === 1, 'generated game saved to the library (' + saved + ')');
  ok(await page.evaluate(() => JSON.parse(localStorage.getItem('nexora.usage'))[new Date().toISOString().slice(0, 7)]) === 1, 'monthly usage counted');

  // code editor, versions, bugfix (local), settings
  await page.click('text=</> Kod');
  ok(await page.locator('.modal textarea.code').inputValue().then(v => v.includes('NexoraRuntime')), 'code editor shows the game source');
  await page.click('text=Spara och kör');
  await page.waitForTimeout(300);
  ok(await page.evaluate(() => Nexora.games.all().then(a => a[0].versions.length)) === 1, 'saving code keeps the previous version');
  await page.click('text=🐞 Buggfix');
  await page.waitForSelector('text=Inga körfel hittades', { timeout: 10000 });
  ok(true, 'bugfix runs the game and reports no runtime errors');
  await page.keyboard.press('Escape');
  await page.click('button[title=Inställningar]');
  await page.selectOption('.modal select', 'anthropic');
  ok(await page.locator('.modal input[type=password]').first().isVisible(), 'settings: Anthropic key field appears');
  await page.selectOption('.modal select', 'local');
  await page.getByRole('button', { name: 'Spara', exact: true }).click();
  await page.waitForTimeout(200);

  // exports produce valid zips
  for (const label of ['PC (Windows, macOS, Linux)', 'Steam', 'Mobil (PWA)', 'Xbox']) {
    await page.click('text=📦 Exportera');
    const card = page.locator('.modal .card .card', { hasText: label });
    const [dl] = await Promise.all([page.waitForEvent('download'), card.locator('button').click()]);
    const p = path.join(SHOTS, dl.suggestedFilename());
    await dl.saveAs(p);
    let good = false;
    try { execFileSync('unzip', ['-tq', p]); good = true; } catch (e) { good = false; }
    ok(good, 'export ' + label + ' → ' + dl.suggestedFilename() + ' is a valid zip');
    await page.keyboard.press('Escape');
  }

  // tools
  await page.evaluate(() => { location.hash = 'verktyg'; });
  await page.waitForTimeout(300);
  const tools = page.locator('.tool');
  for (const name of ['Story', 'Dialog', 'NPC:er', 'Uppdrag', 'Grafik', '3D']) {
    await tools.filter({ hasText: name }).first().locator('button', { hasText: 'Generera' }).click();
    await page.waitForTimeout(250);
  }
  ok((await tools.filter({ hasText: 'Story' }).first().locator('.out').innerText()).includes('Akt 1'), 'story generator writes a story');
  ok(await tools.filter({ hasText: 'Grafik' }).first().locator('.art svg').count() === 1, 'Image 1 (local) draws a sprite');
  await tools.filter({ hasText: 'Musik' }).first().locator('button', { hasText: 'Komponera' }).click();
  await page.waitForSelector('audio', { timeout: 20000 });
  ok(true, 'music generator renders a WAV');
  await page.screenshot({ path: path.join(SHOTS, 'tools-used.png'), fullPage: true });
  ok(errors.length === 0, 'no errors during the whole run ' + (errors.length ? JSON.stringify(errors) : ''));

  // AI providers, with the network mocked: request shape, SSE parsing, thinking stream
  const sent = [];
  const GAME = '<!doctype html><html><head><title>Mock-spelet</title></head><body><canvas id="c"></canvas><script>document.title="Mock-spelet"</' + 'script></body></html>';
  const sse = evs => evs.map(e => 'event: ' + (e.type || 'x') + '\ndata: ' + JSON.stringify(e) + '\n\n').join('');
  await page.route('https://api.anthropic.com/v1/messages', async route => {
    const req = route.request();
    sent.push({ headers: req.headers(), body: JSON.parse(req.postData()) });
    const text = 'Här är spelet:\n```html\n' + GAME + '\n```';
    await route.fulfill({ status: 200, headers: { 'content-type': 'text/event-stream', 'access-control-allow-origin': '*' }, body: sse([
      { type: 'message_start', message: { id: 'msg_1', type: 'message', role: 'assistant', content: [] } },
      { type: 'content_block_start', index: 0, content_block: { type: 'thinking', thinking: '' } },
      { type: 'content_block_delta', index: 0, delta: { type: 'thinking_delta', thinking: 'Planerar nivåerna…' } },
      { type: 'content_block_stop', index: 0 },
      { type: 'content_block_start', index: 1, content_block: { type: 'text', text: '' } },
      { type: 'content_block_delta', index: 1, delta: { type: 'text_delta', text: text.slice(0, 30) } },
      { type: 'content_block_delta', index: 1, delta: { type: 'text_delta', text: text.slice(30) } },
      { type: 'content_block_stop', index: 1 },
      { type: 'message_delta', delta: { stop_reason: 'end_turn' }, usage: { output_tokens: 99 } },
      { type: 'message_stop' },
    ]) });
  });
  await page.evaluate(() => {
    localStorage.setItem('nexora.settings', JSON.stringify({ provider: 'anthropic', anthropicKey: 'sk-ant-test' }));
    localStorage.setItem('nexora.studio', JSON.stringify({ model: 'core', dim: '2d', opts: {}, prompt: 'Ett pusselspel om tid' }));
    location.hash = 'studio'; location.reload();
  });
  await page.waitForSelector('#prompt');
  await page.click('text=✨ Skapa spel');
  await page.waitForSelector('.screen iframe', { timeout: 10000 });
  ok(sent.length === 1, 'Core 1 sent one request to the Messages API');
  const r0 = sent[0];
  ok(r0.body.model === 'claude-opus-5' && r0.body.stream === true && r0.body.thinking && r0.body.thinking.type === 'adaptive' && r0.body.output_config.effort === 'xhigh', 'Core 1 request: opus-5, streaming, adaptive thinking, xhigh effort');
  ok(r0.headers['x-api-key'] === 'sk-ant-test' && r0.headers['anthropic-version'] === '2023-06-01' && r0.headers['anthropic-dangerous-direct-browser-access'] === 'true', 'auth + version + browser headers');
  ok(r0.body.fallbacks === 'default' && r0.headers['anthropic-beta'] === 'server-side-fallback-2026-07-01', 'refusal fallback opted in');
  ok(await page.locator('.bar .title').innerText() === 'Mock-spelet', 'game title taken from the generated HTML');

  await page.evaluate(() => { const s = JSON.parse(localStorage.getItem('nexora.studio')); s.model = 'flash'; localStorage.setItem('nexora.studio', JSON.stringify(s)); location.reload(); });
  await page.waitForSelector('#prompt');
  await page.click('text=✨ Skapa spel');
  await page.waitForSelector('.screen iframe', { timeout: 10000 });
  const r1 = sent[1];
  ok(r1 && r1.body.model === 'claude-haiku-4-5' && !r1.body.thinking && !r1.body.fallbacks && !r1.headers['anthropic-beta'], 'Flash 1 request: haiku-4-5, no thinking, no beta header');

  // refusal surfaces as a readable error
  await page.unroute('https://api.anthropic.com/v1/messages');
  await page.route('https://api.anthropic.com/v1/messages', route => route.fulfill({ status: 200, headers: { 'content-type': 'text/event-stream', 'access-control-allow-origin': '*' }, body: sse([
    { type: 'message_start', message: { id: 'msg_2', content: [] } }, { type: 'message_delta', delta: { stop_reason: 'refusal' } }, { type: 'message_stop' }]) }));
  await page.click('text=✨ Skapa spel');
  await page.waitForSelector('text=avböjde', { timeout: 10000 });
  ok(true, 'refusal shown to the user');
  await page.route('https://api.anthropic.com/v1/messages', route => route.fulfill({ status: 401, headers: { 'content-type': 'application/json', 'access-control-allow-origin': '*' }, body: '{"type":"error","error":{"type":"authentication_error","message":"invalid x-api-key"}}' }));
  await page.click('text=✨ Skapa spel');
  await page.waitForSelector('text=Ogiltig API-nyckel', { timeout: 10000 });
  ok(true, '401 shown as an invalid-key message');

  // OpenAI-compatible endpoint (e.g. the Colab model)
  let oaBody = null;
  await page.route('http://localhost:8000/v1/chat/completions', async route => {
    oaBody = JSON.parse(route.request().postData());
    const chunks = ['```html\n', GAME, '\n```'].map(c => 'data: ' + JSON.stringify({ choices: [{ delta: { content: c } }] }) + '\n\n').join('') + 'data: [DONE]\n\n';
    await route.fulfill({ status: 200, headers: { 'content-type': 'text/event-stream', 'access-control-allow-origin': '*' }, body: chunks });
  });
  await page.evaluate(() => { localStorage.setItem('nexora.settings', JSON.stringify({ provider: 'openai', openaiBase: 'http://localhost:8000/v1', openaiModels: { flash: 'nexora-flash-1' } })); location.reload(); });
  await page.waitForSelector('#prompt');
  await page.click('text=✨ Skapa spel');
  await page.waitForSelector('.screen iframe', { timeout: 10000 });
  ok(oaBody && oaBody.model === 'nexora-flash-1' && oaBody.stream === true && oaBody.messages[0].role === 'system', 'custom endpoint gets an OpenAI-style streaming request');
  await page.evaluate(() => { localStorage.setItem('nexora.settings', JSON.stringify({ provider: 'local' })); });
  errors.length = 0;

  // phone width
  const phone = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await phone.goto('file://' + FILE + '#priser');
  await phone.waitForTimeout(300);
  const overflow = await phone.evaluate(() => document.documentElement.scrollWidth - innerWidth);
  ok(overflow <= 0, 'no horizontal scroll at phone width (' + overflow + 'px)');
  await phone.screenshot({ path: path.join(SHOTS, 'phone-priser.png') });

  await browser.close();
  console.log(failed ? failed + ' FAILED' : 'ALL PASSED');
  process.exit(failed ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
